import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import JSON5 from 'json5';
import { afterEach, describe, expect, it } from 'vitest';
import { buildPages, mergePagesJson } from '@/plugins/vite-plugin-uni-pages';

const tempRoots: string[] = [];

function createProjectRoot(): string {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'unibestx-pages-'));
  tempRoots.push(root);
  return root;
}

function writePage(root: string, relativePath: string): void {
  const filePath = path.join(root, relativePath);
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, '<template><view /></template>\n', 'utf-8');
}

afterEach(() => {
  while (tempRoots.length > 0) {
    fs.rmSync(tempRoots.pop()!, { recursive: true, force: true });
  }
});

describe('uni-pages subpackage scanning', () => {
  it('registers nested pages once when the subpackage root has direct pages and child packages', async () => {
    const root = createProjectRoot();
    writePage(root, 'src/pages/index/index.uvue');
    writePage(root, 'src/sub/rootPage.uvue');
    writePage(root, 'src/sub/child/child.uvue');

    const state = await buildPages(
      {
        dir: 'src/pages',
        subPackages: ['src/sub'],
        subPackageMode: 'subdirs'
      },
      {
        root,
        isProduction: true
      }
    );

    expect(state).not.toBeNull();
    const subPackages = state!.scannedSubPkgs;
    expect(subPackages.map(pkg => pkg.root).sort()).toEqual(['src/sub', 'src/sub/child']);

    const fullPaths = subPackages.flatMap(pkg => pkg.pages.map(page => `${pkg.root}/${page.path}`));
    expect(fullPaths.filter(fullPath => fullPath == 'src/sub/child/child')).toHaveLength(1);

    const rootPackage = subPackages.find(pkg => pkg.root == 'src/sub');
    expect(rootPackage?.pages.map(page => page.path)).toEqual(['rootPage']);
  });

  it('removes stale child pages that were previously registered under the parent package', async () => {
    const root = createProjectRoot();
    writePage(root, 'src/pages/index/index.uvue');
    writePage(root, 'src/sub/rootPage.uvue');
    writePage(root, 'src/sub/child/child.uvue');

    const state = await buildPages(
      {
        dir: 'src/pages',
        subPackages: ['src/sub'],
        subPackageMode: 'subdirs'
      },
      {
        root,
        isProduction: true
      }
    );

    expect(state).not.toBeNull();
    const existing = `{
      "pages": [{ "path": "src/pages/index/index" }],
      "subPackages": [
        {
          "root": "src/sub",
          "pages": [
            // GENERATED BY UNI-PAGES, PLATFORM: APP || H5 || MP
            { "path": "rootPage" },
            { "path": "child/child" }
          ]
        },
        {
          "root": "src/sub/child",
          "pages": [
            // GENERATED BY UNI-PAGES, PLATFORM: APP || H5 || MP
            { "path": "child" }
          ]
        }
      ]
    }`;

    const merged = JSON5.parse(mergePagesJson(existing, state!.output, 'H5', false, [], root));
    const parentPackage = merged.subPackages.find((pkg: any) => pkg.root == 'src/sub');
    expect(parentPackage.pages.map((page: any) => page.path)).toEqual(['rootPage']);
  });
});
